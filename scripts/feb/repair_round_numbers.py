#!/usr/bin/env python3
"""FASE 22.4 — Historical Round-Number Repair (Segunda FEB 2025-2026).

Corrige la jornada real (`data->>'round_number'`) de los 182 partidos que se
ingestaron con `round_number=1` por el fallo de FASE 22.2/22.3 (to_command
hardcodeaba 1; el BoxScore de FEB no lleva la jornada).

NO re-arquitectura: reutiliza `ingest_season.discover_rounds()` (que a su vez usa
`discover_matches.fetch_calendar`/`parse_calendar`) como única fuente de verdad de
la jornada. Genera SQL idempotente que se aplica contra Production PostgreSQL
(por ejemplo vía túnel Railway + psql):

    UPDATE matches
       SET data = jsonb_set(data, '{round_number}', '<rn>'::jsonb)
     WHERE external_id = '<id>'
       AND data->>'round_number' IS DISTINCT FROM '<rn>';

Propiedades:
  * Explicito: solo toca `matches.data->>'round_number'` (metadata de jornada).
  * Idempotente: la cláusula WHERE hace que re-ejecutar sea un no-op.
  * Seguro: no borra, no duplica, no crea external_ids nuevos, no toca
    match_player_stats ni match_team_stats.
  * Sin secrets: el script solo hace el GET público del calendario de FEB y
    escribe SQL por stdout; nunca toca la base (sin credenciales locales).
  * Sin inventar jornadas: si un match no está en el calendario, NO se genera
    UPDATE para él (queda pendiente, se reporta).

Exit codes (coherentes con el resto de scripts FEB):
    0  OK (SQL generado / dry-run)
    2  configuración inválida (temporada no soportada)
    3  error de fuente (fetch/parse del calendario)
    6  error inesperado
"""
from __future__ import annotations

import argparse
import os
import sys
from typing import Dict, List

_HERE = os.path.dirname(os.path.abspath(__file__))
if _HERE not in sys.path:
    sys.path.insert(0, _HERE)

import discover_matches as DM   # noqa: E402  (FASE 22.1)
import ingest_season as IS      # noqa: E402  (FASE 22.3)

DEFAULT_GROUP = "ESTE"


def build_round_map(season_code: str, group: str = DEFAULT_GROUP) -> Dict[str, int]:
    """external_id -> round_number real, usando discovery (una sola fuente: calendario).

    Lanza DM.ConfigError / DM.SourceError igual que el pipeline de discovery.
    """
    by_round = IS.discover_rounds(season_code, group)
    mapping: Dict[str, int] = {}
    for round_number, refs in by_round.items():
        for ref in refs:
            mapping[str(ref.external_id)] = round_number
    return mapping


def render_sql(round_map: Dict[str, int]) -> List[str]:
    """SQL idempotente para corregir `matches.data->>'round_number'` (un UPDATE/match)."""
    sql: List[str] = []
    for external_id in sorted(round_map):
        round_number = round_map[external_id]
        sql.append(
            "UPDATE matches\n"
            "   SET data = jsonb_set(data, '{round_number}', "
            f"'{round_number}'::jsonb)\n"
            f" WHERE external_id = '{external_id}'\n"
            "   AND data->>'round_number' IS DISTINCT FROM "
            f"'{round_number}';\n"
        )
    return sql


def _report_pending(mapping: Dict[str, int], reported: set) -> None:
    missing = [ext for ext in mapping if ext not in reported]
    if missing:
        print(f"NOT_IN_CALENDAR: {len(missing)} external_ids sin jornada real (sin UPDATE):")
        for ext in sorted(missing):
            print(f"  {ext}")
        print()


def run() -> int:
    ap = argparse.ArgumentParser(prog="feb-repair-rounds")
    ap.add_argument("--season", required=True, help="season code (default env FEB_SEASON_CODE or 2025-2026)")
    ap.add_argument("--group", default=DEFAULT_GROUP, help=f"group (default {DEFAULT_GROUP})")
    ap.add_argument("--dry-run", action="store_true",
                    help="mostrar el mapeo external_id->round (sin SQL)")
    args = ap.parse_args()

    try:
        round_map = build_round_map(args.season, args.group)
    except DM.ConfigError as exc:
        print(f"CONFIG_ERROR: {exc}", file=sys.stderr)
        return 2
    except DM.SourceError as exc:
        print(f"SOURCE_ERROR: {exc}", file=sys.stderr)
        return 3
    except Exception as exc:  # noqa: BLE001 — CLI boundary: unexpected -> 6
        print(f"UNEXPECTED_ERROR: {exc}", file=sys.stderr)
        return 6

    print(f"FASE 22.4 ROUND REPAIR  season={args.season} group={args.group}")
    print(f"mapped={len(round_map)} external_ids")
    print()
    if args.dry_run:
        for external_id in sorted(round_map):
            print(f"{external_id} -> round={round_map[external_id]}")
        print()
        print("DRY_RUN: no SQL emitted")
        return 0

    sql = render_sql(round_map)
    if not sql:
        print("no round corrections to emit")
        return 0
    print("-- generated by feb-score repair_round_numbers.py (FASE 22.4) --")
    print("-- apply via: PGPASSWORD=postgres psql -h 127.0.0.1 -p 15433 -U postgres -d railway -f - < file.sql")
    print()
    for stmt in sql:
        print(stmt)
    return 0


if __name__ == "__main__":
    sys.exit(run())