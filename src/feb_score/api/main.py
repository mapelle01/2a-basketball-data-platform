"""FASE 11 + FASE 13 — HTTP application factory.

Boundary: ``/v1``. Every command endpoint translates HTTP -> Command and delegates
to the ``CommandGateway`` (-> CommandRunner -> handlers). No business logic, no
concrete repositories, no SQLite, no aggregates live here. Contract validation is
NOT re-implemented: the versioned JSON-Schemas remain the single source of truth
(validated by the Application's ``contract_validated`` decorator).

Security (FASE 13): the client NEVER declares its role. An ``AuthenticationProvider``
establishes the principal (identity + role) from a real credential; the role is
then authorized per-command before the request reaches the gateway. The domain
``Actor`` is derived from the authenticated principal, so ``role=admin`` cannot be
forged in the request body or command payload.
"""

